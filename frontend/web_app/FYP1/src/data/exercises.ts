export type MuscleGroup = 'Chest' | 'Biceps' | 'Back' | 'Triceps' | 'Abdominal' | 'Legs' | 'Shoulders';
export type Goal = 'gain' | 'loss' | 'maintenance';
export type Level = 'easy' | 'intermediate' | 'hard';
export type AgeGroup = 'children' | 'adults' | 'older';

export interface Exercise {
  name: string;
  muscleGroup: MuscleGroup;
  goal: Goal[];
  level: Level;
  ageGroup: AgeGroup[];
  equipment: string;
  description: string;
  reps: string;
  sets: number;
  restTime: number;
  calories: number;
  formTips: string[];
  isTimeBased?: boolean;
}

export const weeklySchedule: Record<string, string> = {
  'Monday': 'Chest',
  'Tuesday': 'Biceps/Triceps',
  'Wednesday': 'Back',
  'Thursday': 'Shoulders',
  'Friday': 'Abdominal',
  'Saturday': 'Legs',
  'Sunday': 'Rest'
};

// Helper function to get age group
export function getAgeGroup(age: number): AgeGroup {
  if (age >= 10 && age <= 16) return 'children';
  if (age >= 17 && age <= 45) return 'adults';
  return 'older';
}

// Helper function to get level based on experience months
export function getLevel(experienceMonths: number): Level {
  if (experienceMonths < 6) return 'easy';
  if (experienceMonths < 18) return 'intermediate';
  return 'hard';
}

// Helper function to get today's muscle group
export function getTodaysMuscleGroup(): string {
  const days = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
  const today = days[new Date().getDay()];
  return weeklySchedule[today] || 'Rest';
}

// Helper function to filter exercises
export function getFilteredExercises(
  muscleGroup: MuscleGroup,
  goal: Goal,
  level: Level,
  ageGroup: AgeGroup
): Exercise[] {
  return exerciseDatabase.filter(exercise => {
    const matchesMuscleGroup = exercise.muscleGroup === muscleGroup;
    const matchesGoal = exercise.goal.includes(goal);
    const matchesLevel = exercise.level === level;
    const matchesAgeGroup = exercise.ageGroup.includes(ageGroup);
    
    return matchesMuscleGroup && matchesGoal && matchesLevel && matchesAgeGroup;
  });
}

